-- Esquema inicial da clinica. Gerado a partir das entidades JPA (dialeto PostgreSQL) e
-- revisado: nomes de restricoes legiveis, chave primaria em usuario_perfil e indices nas
-- chaves estrangeiras mais consultadas (o PostgreSQL nao os cria sozinho).
--
-- Regra do Flyway: um arquivo ja aplicado nunca e alterado. Qualquer mudanca no esquema
-- entra em um novo arquivo, V2__..., V3__...

-- ---------- Contas de acesso ----------

create table perfis (
    id   bigint generated by default as identity primary key,
    nome varchar(40) not null,
    constraint uk_perfil_nome unique (nome)
);

create table usuarios (
    id                bigint generated by default as identity primary key,
    login             varchar(80)  not null,
    password          varchar(255) not null,
    ativo             boolean      not null,
    tentativas_falhas integer      not null default 0,
    bloqueado_ate     timestamp(6),
    constraint uk_usuario_login unique (login)
);

create table usuario_perfil (
    usuario_id bigint not null,
    perfil_id  bigint not null,
    constraint pk_usuario_perfil primary key (usuario_id, perfil_id),
    constraint fk_usuario_perfil_usuario foreign key (usuario_id) references usuarios (id),
    constraint fk_usuario_perfil_perfil foreign key (perfil_id) references perfis (id)
);

-- ---------- Pessoas ----------

create table pacientes (
    id               bigint generated by default as identity primary key,
    nome             varchar(120) not null,
    cpf              varchar(14)  not null,
    data_nascimento  date         not null,
    telefone         varchar(20),
    email            varchar(120),
    consentimento_em timestamp(6),
    usuario_id       bigint,
    constraint uk_paciente_cpf unique (cpf),
    constraint uk_paciente_usuario unique (usuario_id),
    constraint fk_paciente_usuario foreign key (usuario_id) references usuarios (id)
);

create table medicos (
    id            bigint generated by default as identity primary key,
    nome          varchar(120) not null,
    crm           varchar(20)  not null,
    especialidade varchar(80)  not null,
    telefone      varchar(20),
    email         varchar(120),
    usuario_id    bigint,
    constraint uk_medico_crm unique (crm),
    constraint uk_medico_usuario unique (usuario_id),
    constraint fk_medico_usuario foreign key (usuario_id) references usuarios (id)
);

-- ---------- Agenda, agendamentos e consultas ----------

create table agendas (
    id        bigint generated by default as identity primary key,
    medico_id bigint      not null,
    data      date        not null,
    horario   time(0)     not null,
    status    varchar(20) not null,
    constraint ck_agenda_status check (status in ('DISPONIVEL', 'AGENDADO')),
    constraint uk_agenda_medico_data_horario unique (medico_id, data, horario),
    constraint fk_agenda_medico foreign key (medico_id) references medicos (id)
);
-- Agenda do dia e horarios livres de todos os medicos filtram pela data.
create index ix_agenda_data on agendas (data, horario);

-- reserva_ativa: TRUE enquanto o agendamento ocupa o horario, NULL depois de cancelado.
-- Com a restricao unica abaixo, cada horario tem no maximo um agendamento ativo (ver Agendamento).
create table agendamentos (
    id                  bigint generated by default as identity primary key,
    agenda_id           bigint       not null,
    paciente_id         bigint       not null,
    data_criacao        timestamp(6) not null,
    status              varchar(20)  not null,
    reserva_ativa       boolean,
    data_cancelamento   timestamp(6),
    cancelado_por       varchar(50),
    motivo_cancelamento varchar(255),
    constraint ck_agendamento_status check (status in ('AGENDADO', 'REALIZADO', 'FALTOU', 'CANCELADO')),
    constraint uk_agendamento_reserva_ativa unique (agenda_id, reserva_ativa),
    constraint fk_agendamento_agenda foreign key (agenda_id) references agendas (id),
    constraint fk_agendamento_paciente foreign key (paciente_id) references pacientes (id)
);
create index ix_agendamento_paciente on agendamentos (paciente_id);

create table consultas (
    id              bigint generated by default as identity primary key,
    agendamento_id  bigint       not null,
    data_realizacao timestamp(6) not null,
    observacoes     varchar(500),
    constraint uk_consulta_agendamento unique (agendamento_id),
    constraint fk_consulta_agendamento foreign key (agendamento_id) references agendamentos (id)
);

-- ---------- Auditoria ----------

create table auditoria (
    id          bigint generated by default as identity primary key,
    data_hora   timestamp(6) not null,
    usuario     varchar(80)  not null,
    acao        varchar(40)  not null,
    entidade    varchar(40),
    entidade_id bigint,
    detalhe     varchar(500),
    constraint ck_auditoria_acao check (acao in (
        'LOGIN', 'LOGIN_FALHOU', 'CONTA_BLOQUEADA',
        'HORARIO_CADASTRADO', 'HORARIOS_GERADOS',
        'AGENDAMENTO_CRIADO', 'AGENDAMENTO_CANCELADO', 'AGENDAMENTO_REAGENDADO',
        'PRESENCA_CONFIRMADA', 'FALTA_REGISTRADA', 'CONSULTA_ALTERADA',
        'PACIENTE_CADASTRADO', 'PACIENTE_ALTERADO', 'PACIENTE_EXCLUIDO',
        'MEDICO_CADASTRADO', 'MEDICO_ALTERADO', 'MEDICO_EXCLUIDO',
        'DADOS_EXPORTADOS'))
);
create index ix_auditoria_data_hora on auditoria (data_hora);
create index ix_auditoria_usuario on auditoria (usuario);

